/// 货场（场地）标准名与别名归一。
///
/// 队长表格里货场写法极不统一：有的写在表/区域标题（「南货场绩效」「56道货场
/// 绩效表」），有的嵌在列名（「入库归垛S26.S27」），有的写在备注（「五六道」）。
/// 这里统一归一成系统标准名，供导入识别、统计分组、首页/历史筛选复用。
class Yards {
  Yards._();

  /// 系统标准货场名（统计分组、下拉选项以此为准）。
  static const List<String> standardYards = [
    '南货场',
    '45万货场',
    '26万货场',
    '27万货场',
    '56道',
    '前场',
    '神华',
  ];

  /// 别名关键字 → 标准名。匹配靠 [canonicalYard] 的关键字包含判断，
  /// 顺序在 [canonicalYard] 内部已按"字多优先"排列以避免歧义（如「南27货场」先于「27万」）。
  static const Map<String, String> aliasToStandard = {
    '南货场': '南货场',
    '南场': '南货场',
    '45万货场': '45万货场',
    '45万场': '45万货场',
    '45万': '45万货场',
    '26万货场': '26万货场',
    '26货场': '26万货场',
    '26万': '26万货场',
    '27万货场': '27万货场',
    '27货场': '27万货场',
    '南27货场': '27万货场',
    '27万': '27万货场',
    '56道': '56道',
    '5、6道': '56道',
    '5.6道': '56道',
    '五六道': '56道',
    '前场': '前场',
    '神华': '神华',
    '神港': '神华',
  };

  /// 把标题 / 列名 / 备注里的文字归一为货场标准名；识别不出返回 null。
  ///
  /// 关键字按"多字优先"依次匹配，避免「南27货场」被「27万」误截、或「56道货场
  /// 绩效表」被「南货场」误中（它其实不含「南货场」）。
  static String? canonicalYard(String text) {
    if (text.isEmpty) return null;
    final t = text.replaceAll(RegExp(r'\s+'), '');
    const ordered = <String>[
      '南27货场',
      '27万货场',
      '27货场',
      '27万',
      '26万货场',
      '26货场',
      '26万',
      '45万货场',
      '45万场',
      '45万',
      '5、6道',
      '5.6道',
      '五六道',
      '56道',
      '前场',
      '神华',
      '神港',
      '南场',
      '南货场',
    ];
    for (final key in ordered) {
      if (t.contains(key)) return aliasToStandard[key]!;
    }
    return null;
  }

  /// 是否已知标准货场名（用于区分新格式导入记录中的货场段与旧格式船名段）。
  static bool isStandard(String name) => standardYards.contains(name);
}
